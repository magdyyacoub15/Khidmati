new_content = content
for lang, trans in translations.items():
    # Example format: 'fr': {
    pattern = r"('" + lang + r"':\s*\{)"
    match = re.search(pattern, new_content)
    if match:
        insert_str = "\n"
        for k, v in trans.items():
            # escape single quotes
            v_escaped = v.replace("'", "\\'")
            insert_str += f"      '{k}': '{v_escaped}',\n"
        
        insert_pos = match.end()
        new_content = new_content[:insert_pos] + insert_str + new_content[insert_pos:]
    else:
        print(f"Language {lang} not found!")

with open(file_path, 'w', encoding='utf-8') as f:
    f.write(new_content)

